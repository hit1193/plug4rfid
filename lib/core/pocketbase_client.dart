import 'package:pocketbase/pocketbase.dart';
import 'package:flutter/foundation.dart'; // 웹(Web) 환경 판별(kIsWeb)을 위해 추가
import 'dart:io';                         // 운영체제(Platform) 판별을 위해 추가

/// ---------------------------------------------------------------------------
/// [포켓베이스 서버 URL 동적 할당 함수]
/// 실행되는 기기의 환경을 스스로 분석하여 올바른 서버 주소를 반환합니다.
/// ---------------------------------------------------------------------------
String _getSmartServerUrl() {
  // 1. 웹(Web) 브라우저 환경인 경우
  if (kIsWeb) {
    return 'http://127.0.0.1:8090';
  }

  // 2. 안드로이드(Android) 환경인 경우
  if (Platform.isAndroid) {
    // [중요] 안드로이드 에뮬레이터에서는 PC의 localhost에 접근하기 위해 10.0.2.2를 사용해야 합니다.
    // 만약 에뮬레이터가 아니라 '실제 스마트폰/태블릿 기기'로 테스트하신다면,
    // 아래 주소를 주석 처리하고 PC의 실제 내부 IP (예: 'http://192.168.0.15:8090')를 입력하세요.
    return 'http://10.0.2.2:8090';
  }

  // 3. 데스크톱(Windows, macOS, Linux) 환경인 경우
  // PC용 프로그램으로 빌드되어 실행될 때는 로컬호스트를 그대로 사용합니다.
  return 'http://127.0.0.1:8090';
}

/// ---------------------------------------------------------------------------
/// [전역 포켓베이스 클라이언트 인스턴스 (pb)]
/// 앱 전체에서 사용할 단일(Singleton) 데이터베이스 연결 객체입니다.
/// _getSmartServerUrl() 함수를 호출하여 환경에 맞는 URL로 초기화합니다.
/// ---------------------------------------------------------------------------
final PocketBase pb = PocketBase(_getSmartServerUrl());